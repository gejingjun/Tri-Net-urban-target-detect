#!/usr/bin/env python3
"""Generate a small SYNTHETIC tri-modal sample dataset in the UrbanTraffic-3M
layout so the whole repo can be smoke-tested without the real data:

    data/fake/images|ir|depth|labels/{train,val}/...

Each scene contains random rectangles ("targets") drawn into RGB/IR with a
correlated appearance + thermal signature; depth is metric uint16 (mm) with
~28% structurally-invalid pixels (matching the paper's 28.3% statistic).

Usage:
    python scripts/make_fake_data.py --out data/fake --n 24
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np

CLASSES = ["person", "animal", "car", "light", "sign", "bicycle",
           "seat", "garbagecan", "uav", "boat", "ball", "tricycle"]
BATCHES = ["numeric", "seq6_3_8", "shuming", "hehe", "seq_suppl"]
CONDITIONS = ["day_clear", "night_clear", "night_glare", "backlight", "fog"]


def make_scene(rng, batch, cond):
    H = W = 640
    rgb = np.full((H, W, 3), (110, 110, 110), np.uint8)
    ir = np.full((H, W), 60, np.uint8)
    dep = np.zeros((H, W), np.uint16)
    # background plane at ~12 m
    dep[:] = 12000
    n_boxes = int(rng.integers(2, 7))
    lb = []
    for bi in range(n_boxes):
        cls = int(rng.integers(0, len(CLASSES)))
        cx, cy = rng.integers(60, W - 60), rng.integers(60, H - 60)
        bw = int(rng.integers(8, 120))          # includes small targets
        bh = int(max(8, bw * rng.uniform(0.5, 2.0)))
        x1, y1, x2, y2 = cx - bw // 2, cy - bh // 2, cx + bw // 2, cy + bh // 2
        color = rng.integers(0, 255, 3)
        rgb[y1:y2, x1:x2] = color
        ir[y1:y2, x1:x2] = int(200 if cls in (0, 1, 5) else 90)  # warm/cold bodies
        d = int(rng.integers(3500, 19500))
        dep[y1:y2, x1:x2] = d
        lb.append([cls, cx / W, cy / H, bw / W, bh / H])
    # structurally invalid depth: ~28.3% pixels zero (textureless sky/road)
    hole = rng.random((H, W)) < 0.283
    dep[hole] = 0
    if cond == "fog":
        rgb = cv2.addWeighted(rgb, 0.55, np.full_like(rgb, 200), 0.45, 0)
    if cond == "night_clear":
        rgb = (rgb * 0.25).astype(np.uint8)
    if cond == "night_glare":
        rgb = np.clip(rgb.astype(np.int32) + 60, 0, 255).astype(np.uint8)
        rgb[:60, :] = 255
    return rgb, ir[..., None], dep, np.array(lb, np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/fake")
    ap.add_argument("--n", type=int, default=24, help="total images")
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--pseudo-depth-frac", type=float, default=0.155,
                    help="fraction using uint8 pseudo-depth (paper: 15.5%%)")
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    root = Path(args.out)
    meta = {"train": {}, "val": {}}
    for split, n in (("train", int(args.n * 2 / 3)), ("val", args.n - int(args.n * 2 / 3))):
        for d in ("images", "ir", "depth", "labels", "meta"):
            (root / d / split).mkdir(parents=True, exist_ok=True)
        for i in range(n):
            batch = str(rng.choice(BATCHES))
            cond = str(rng.choice(CONDITIONS))
            seq = int(rng.integers(1, 9))
            stem = f"{batch}_{seq:02d}_{i:07d}"
            rgb, ir, dep, lb = make_scene(rng, batch, cond)
            pseudo = rng.random() < args.pseudo_depth_frac
            if pseudo:
                dep2 = ((dep.astype(np.float32) / 20000.0) * 255).astype(np.uint8)
                cv2.imwrite(str(root / "depth" / split / f"{stem}.png"), dep2)
            else:
                cv2.imwrite(str(root / "depth" / split / f"{stem}.png"), dep)
            cv2.imwrite(str(root / "images" / split / f"{stem}.png"), rgb)
            cv2.imwrite(str(root / "ir" / split / f"{stem}.png"), ir)
            np.savetxt(root / "labels" / split / f"{stem}.txt", lb,
                       fmt="%.5f")
            meta[split][stem] = {"batch": batch, "condition": cond,
                                 "sequence": f"{batch}_{seq:02d}"}
        (root / "meta").mkdir(exist_ok=True)
        (root / "meta" / f"{split}.json").write_text(
            json.dumps(meta[split], indent=1), encoding="utf-8")
    (root / "README.md").write_text(
        f"# Synthetic sample data\nGenerated by scripts/make_fake_data.py "
        f"(seed={args.seed}, n={args.n}). Layout documented there. "
        f"NOT for scientific use — smoke tests only.\n", encoding="utf-8")
    print(f"fake data -> {root.resolve()}  train={len(meta['train'])} val={len(meta['val'])}")


if __name__ == "__main__":
    main()
